package com.norbertfila.world;

public final class BlockId {
    public static final byte AIR = 0,
            GRASS = 1,
            DIRT = 2,
            STONE = 3,
            SAND = 4,
            GRAVEL = 5,
            BEDROCK = 6,
            SNOW = 7,
            LOG = 8,
            LEAVES = 9,
            PLANKS = 10,
            COBBLE = 11,
            BRICKS = 12,
            GLASS = 13,
            SANDSTONE = 14,
            STONE_BRICKS = 15,
            WATER = 16,
            SHORT_GRASS = 17,
            FERN = 18,
            DANDELION_YELLOW = 19,
            DANDELION_WHITE = 20,
            POPPY = 21,
            MUD = 22,
            PODZOL = 23,
            COARSE_DIRT = 24,
            CLAY = 25,
            TERRACOTTA_RED = 26,
            TERRACOTTA_ORANGE = 27,
            ICE = 28,
            PACKED_ICE = 29,
            DRY_GRASS = 30,
            CACTUS = 31,
            DEAD_BUSH = 32,
            REED = 33,
            MUSHROOM = 34,
            BERRY_BUSH = 35,
            ALPINE_GRASS = 36,
            PINE_LOG = 37,
            PINE_NEEDLES = 38,
            SWAMP_LOG = 39,
            SWAMP_LEAVES = 40,
            SNOW_LAYER = 41,
            COAL_ORE = 42,
            IRON_ORE = 43,
            GOLD_ORE = 44,
            DIAMOND_ORE = 45,
            LAPIS_ORE = 46;

    public static int toUnsignedInt(byte id) {
        return Byte.toUnsignedInt(id);
    }

    public static boolean isValid(byte id) {
        return switch (toUnsignedInt(id)) {
            case AIR,
                    GRASS,
                    DIRT,
                    STONE,
                    SAND,
                    GRAVEL,
                    BEDROCK,
                    SNOW,
                    LOG,
                    LEAVES,
                    PLANKS,
                    COBBLE,
                    BRICKS,
                    GLASS,
                    SANDSTONE,
                    STONE_BRICKS,
                    WATER,
                    SHORT_GRASS,
                    FERN,
                    DANDELION_YELLOW,
                    DANDELION_WHITE,
                    POPPY,
                    MUD,
                    PODZOL,
                    COARSE_DIRT,
                    CLAY,
                    TERRACOTTA_RED,
                    TERRACOTTA_ORANGE,
                    ICE,
                    PACKED_ICE,
                    DRY_GRASS -> true;
            case CACTUS,
                    DEAD_BUSH,
                    REED,
                    MUSHROOM,
                    BERRY_BUSH,
                    ALPINE_GRASS,
                    PINE_LOG,
                    PINE_NEEDLES,
                    SWAMP_LOG,
                    SWAMP_LEAVES,
                    SNOW_LAYER,
                    COAL_ORE,
                    IRON_ORE,
                    GOLD_ORE,
                    DIAMOND_ORE,
                    LAPIS_ORE -> true;
            default -> false;
        };
    }

    private BlockId() {}
}
